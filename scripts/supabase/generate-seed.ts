/**
 * Writes the built-in website content into supabase/schema.sql as seed rows
 * for `site_content`, between the SEED markers. Run after changing anything in
 * src/content/:
 *
 *   npm run db:seed-sql
 *
 * Seed rows use ON CONFLICT DO NOTHING, so re-running the SQL never
 * overwrites edits made in the admin dashboard.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { sectionDefaults, sectionInfo, sectionKeys } from "../../src/lib/content/sections";

const FILE = path.join(process.cwd(), "supabase", "schema.sql");
const START = "-- >>> SEED: site content (generated by `npm run db:seed-sql` — do not edit by hand)";
const END = "-- <<< SEED: end";
const TAG = "$seed$";

const rows = sectionKeys.map((key) => {
  const json = JSON.stringify(sectionDefaults[key], null, 2);
  if (json.includes(TAG)) throw new Error(`Section ${key} contains ${TAG}; pick another dollar-quote tag.`);
  return `-- ${sectionInfo[key].label}\ninsert into public.site_content (key, value) values ('${key}', ${TAG}${json}${TAG}::jsonb)\non conflict (key) do nothing;`;
});

const block = [
  START,
  "-- Every editable section of the website, as it ships. Existing rows are left",
  "-- untouched, so running this file again never overwrites dashboard edits.",
  "-- To restore one section to this seed, use \"Reset to default\" in the",
  "-- dashboard (or delete its row) and run the file again.",
  "begin;",
  ...rows,
  "commit;",
  END,
].join("\n\n");

const sql = readFileSync(FILE, "utf8");
const i = sql.indexOf(START);
const j = sql.indexOf(END);
const next =
  i >= 0 && j > i ? sql.slice(0, i) + block + sql.slice(j + END.length) : `${sql.trimEnd()}\n\n${block}\n`;
writeFileSync(FILE, next);
console.log(`Seeded ${rows.length} content sections into ${path.relative(process.cwd(), FILE)}`);
