"""
Generates src/components/map/mumbai-boundary.ts — the simplified, projected
outline of Mumbai used by the Section 09 map.

Source: OpenStreetMap administrative boundaries, via Nominatim:
  relation 7964376  Mumbai City District
  relation 7964375  Mumbai Suburban District
Map data © OpenStreetMap contributors, available under the ODbL.

Usage:
  python3 scripts/mumbai-map/generate.py [cache_dir]

Downloads are cached in cache_dir (default: .cache/mumbai-map) and requests
follow the Nominatim usage policy (identifying User-Agent, one request/sec).
"""

import json
import math
import os
import sys
import time
import urllib.parse
import urllib.request

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
CACHE = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, ".cache", "mumbai-map")
OUT = os.path.join(ROOT, "src", "components", "map", "mumbai-boundary.ts")
USER_AGENT = "InnovaHack-website-map-generator/1.0"

DISTRICTS = {
    "city": "Mumbai City District, Maharashtra, India",
    "suburban": "Mumbai Suburban District, Maharashtra, India",
}

# Map frame in degrees, and output width in SVG units.
LON0, LON1 = 72.765, 73.0
LAT0, LAT1 = 18.885, 19.28
WIDTH = 600
KX = math.cos(math.radians((LAT0 + LAT1) / 2))
SCALE = WIDTH / ((LON1 - LON0) * KX)
HEIGHT = round((LAT1 - LAT0) * SCALE)

TOLERANCE = 0.6  # px, Douglas–Peucker
MIN_AREA = 25  # px², drops specks


def fetch(key, query):
    os.makedirs(CACHE, exist_ok=True)
    path = os.path.join(CACHE, f"{key}.json")
    if not os.path.exists(path):
        url = "https://nominatim.openstreetmap.org/search?" + urllib.parse.urlencode(
            {"q": query, "polygon_geojson": 1, "format": "json", "limit": 1}
        )
        req = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
        with urllib.request.urlopen(req, timeout=60) as res, open(path, "wb") as f:
            f.write(res.read())
        time.sleep(1.1)
    with open(path) as f:
        result = json.load(f)[0]
    geo = result["geojson"]
    polys = geo["coordinates"] if geo["type"] == "MultiPolygon" else [geo["coordinates"]]
    return [ring for poly in polys for ring in poly]


def proj(lon, lat):
    return ((lon - LON0) * KX * SCALE, (LAT1 - lat) * SCALE)


def rdp(points, eps):
    if len(points) < 3:
        return points
    (x1, y1), (x2, y2) = points[0], points[-1]
    dx, dy = x2 - x1, y2 - y1
    norm = math.hypot(dx, dy) or 1e-9
    best, index = 0.0, 0
    for i in range(1, len(points) - 1):
        px, py = points[i]
        d = abs(dy * px - dx * py + x2 * y1 - y2 * x1) / norm
        if d > best:
            best, index = d, i
    if best <= eps:
        return [points[0], points[-1]]
    return rdp(points[: index + 1], eps)[:-1] + rdp(points[index:], eps)


def simplify_ring(points, eps):
    # A closed ring starts and ends on the same point, which would collapse
    # Douglas–Peucker; split it at the point farthest from the start instead.
    x0, y0 = points[0]
    far = max(range(len(points)), key=lambda i: math.hypot(points[i][0] - x0, points[i][1] - y0))
    return rdp(points[: far + 1], eps)[:-1] + rdp(points[far:], eps)


def area(points):
    return abs(sum(x1 * y2 - x2 * y1 for (x1, y1), (x2, y2) in zip(points, points[1:] + points[:1]))) / 2


def to_path(rings):
    parts = []
    for ring in rings:
        pts = [proj(lon, lat) for lon, lat in ring]
        if area(pts) < MIN_AREA:
            continue
        pts = simplify_ring(pts, TOLERANCE)
        parts.append("M" + "L".join(f"{x:.1f} {y:.1f}" for x, y in pts) + "Z")
    return "".join(parts)


def main():
    sys.setrecursionlimit(10000)
    paths = {key: to_path(fetch(key, query)) for key, query in DISTRICTS.items()}
    with open(OUT, "w") as f:
        f.write(
            "// Generated by scripts/mumbai-map/generate.py — do not edit by hand.\n"
            "// Map data © OpenStreetMap contributors, available under the ODbL.\n"
            "// Mumbai City District (relation 7964376) and Mumbai Suburban District (relation 7964375).\n\n"
            f"export const frame = {{ lon0: {LON0}, lon1: {LON1}, lat0: {LAT0}, lat1: {LAT1}, "
            f"width: {WIDTH}, height: {HEIGHT}, kx: {KX:.6f}, scale: {SCALE:.4f} }};\n\n"
            f'export const cityDistrictPath =\n  "{paths["city"]}";\n\n'
            f'export const suburbanDistrictPath =\n  "{paths["suburban"]}";\n'
        )
    print(f"wrote {OUT} ({os.path.getsize(OUT) // 1024} KB), {WIDTH}x{HEIGHT}")


if __name__ == "__main__":
    main()
